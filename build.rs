//! Generates the embedded-locale table from the selected Cargo features.
//!
//! This is the Rust counterpart of the `//go:embed`-plus-build-tags
//! arrangement a Go port needs: the default (`all-languages`) embeds
//! every `data/*.sor` file, and a consumer who only needs a few opts
//! into `lang-<code>` features instead - see "Selecting which languages
//! get embedded" in README.md.
//!
//! Doing the selection here rather than with `#[cfg(feature = ...)]` in
//! hand-written source keeps the rule that adding a language is a data
//! change: a new `data/<code>.sor` plus a regenerated feature list
//! (`make gen-features`), never a new source file.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(
        env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set by cargo"),
    );
    let data_dir = manifest_dir.join("data");

    // A locale added, removed, or edited has to re-run this; the *.sor
    // contents themselves are pulled in by include_str!, which cargo
    // tracks on its own.
    println!("cargo:rerun-if-changed={}", data_dir.display());
    println!("cargo:rerun-if-changed=build.rs");

    let codes = locale_codes(&data_dir);
    let embed_all = env::var_os("CARGO_FEATURE_ALL_LANGUAGES").is_some();

    let selected: BTreeMap<&str, &Path> = codes
        .iter()
        .filter(|(code, _)| embed_all || env::var_os(feature_env_var(code)).is_some())
        .map(|(code, path)| (code.as_str(), path.as_path()))
        .collect();

    let mut out = String::new();
    out.push_str(
        "// Generated by build.rs from the selected `lang-*` Cargo features. Do not edit.\n\
         /// Every locale embedded into this build, as `(code, sor_source)`.\n\
         pub(crate) static EMBEDDED_LOCALES: &[(&str, &str)] = &[\n",
    );

    for (code, path) in &selected {
        writeln!(
            out,
            "    ({code:?}, include_str!({:?})),",
            path.to_str().expect("locale path must be valid UTF-8")
        )
        .expect("writing to a String cannot fail");
    }

    out.push_str("];\n");

    let dest = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is always set by cargo"))
        .join("embedded_locales.rs");
    fs::write(&dest, out).expect("failed to write the generated locale table");
}

/// Lists the bundled locales as `(code, absolute path)`, sorted by code.
///
/// The code is the file's base name exactly as upstream spells it
/// (`en`, `pt`, `hu_Hung`), since that is what a caller passes as a
/// language code.
fn locale_codes(data_dir: &Path) -> Vec<(String, PathBuf)> {
    let entries = fs::read_dir(data_dir).unwrap_or_else(|err| {
        panic!(
            "cannot read the bundled locale directory {}: {err}",
            data_dir.display()
        )
    });

    let mut codes: Vec<(String, PathBuf)> = entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "sor"))
        .filter_map(|path| {
            let code = path.file_stem()?.to_str()?.to_owned();
            Some((code, path))
        })
        .collect();

    codes.sort();
    assert!(
        !codes.is_empty(),
        "no data/*.sor files found in {} - run scripts/sync-data.sh",
        data_dir.display()
    );

    codes
}

/// The environment variable cargo sets for a locale's opt-in feature.
///
/// Cargo uppercases the feature name and replaces `-` with `_`, so
/// `hu_Hung` -> feature `lang-hu-hung` -> `CARGO_FEATURE_LANG_HU_HUNG`.
/// This must stay in step with `scripts/gen-locale-features.py`, which
/// writes the feature names into Cargo.toml.
fn feature_env_var(code: &str) -> String {
    format!(
        "CARGO_FEATURE_LANG_{}",
        code.to_uppercase().replace('-', "_")
    )
}
